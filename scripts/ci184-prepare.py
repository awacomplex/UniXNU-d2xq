#!/usr/bin/env python3
"""Prepare checked CI184 RECOVERY payloads without changing original chunks.

Examples:
  python scripts/ci184-prepare.py manifest --chunks-dir E:/d2xq-work/chunks
  python scripts/ci184-prepare.py wrap --chunks-dir E:/d2xq-work/chunks --out-dir E:/d2xq-work/ci184 --mode repair --slot 1
  python scripts/ci184-prepare.py wrap --chunks-dir E:/d2xq-work/chunks --out-dir E:/d2xq-work/ci184 --mode append --all
  python scripts/ci184-prepare.py verify --file E:/d2xq-work/ci184/repair_001.bin

Metadata occupies the 4 KiB block immediately after a 64 MiB payload.  All
integers are little endian.  The 128-byte header consists of the packed 96-byte
fields below followed by SHA256(header[0:96]); the rest of the block is zero.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import sys
import uuid

SCRIPT_DIR = Path(__file__).resolve().parent
MANIFEST_PATH = SCRIPT_DIR / "ci184-chunk-manifest.json"
HASH_TABLE_PATH = SCRIPT_DIR / "ci184-chunk-hashes.inc"
BLOCK_BYTES = 4096
CHUNK_BLOCKS = 16384
CHUNK_BYTES = BLOCK_BYTES * CHUNK_BLOCKS
TOTAL_CHUNKS = 140
IMAGE_BYTES = 9382658048
IMAGE_SHA256 = "fd43ee7035ce185ce4215ac93fdc006fd784a54b3b7442e21457c226cbe03093"
USERDATA_FIRST = 0x21F400
USERDATA_LAST = 0x3B90BFA
RECOVERY_FIRST = 0x24F13
MAGIC = b"D2XQIN2\0"
VERSION = 2
HEADER_BYTES = 128
MODE_VALUES = {"repair": 1, "append": 2}
HEADER_FIELDS = struct.Struct("<8sIIIIQQ32sQQQ")
assert HEADER_FIELDS.size == 96


def digest_file(path, byte_count=None):
    sha = hashlib.sha256()
    remaining = byte_count
    with Path(path).open("rb") as source:
        while remaining is None or remaining:
            size = 1024 * 1024 if remaining is None else min(1024 * 1024, remaining)
            data = source.read(size)
            if not data:
                if remaining:
                    raise ValueError(f"short payload: {path}")
                break
            sha.update(data)
            if remaining is not None:
                remaining -= len(data)
    return sha.hexdigest()


def write_source_file(path, text):
    path = Path(path)
    temporary = path.with_name(path.name + ".tmp-" + uuid.uuid4().hex)
    try:
        temporary.write_text(text, encoding="utf-8", newline="\n")
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def generate_manifest(chunks_dir):
    chunks_dir = Path(chunks_dir)
    chunks = []
    image_sha = hashlib.sha256()
    image_remaining = IMAGE_BYTES
    for slot in range(TOTAL_CHUNKS):
        name = f"chunk_{slot:03d}.bin"
        source = chunks_dir / name
        if source.stat().st_size != CHUNK_BYTES:
            raise ValueError(f"expected {CHUNK_BYTES} bytes: {source}")
        chunk_sha = hashlib.sha256()
        with source.open("rb") as stream:
            while True:
                data = stream.read(1024 * 1024)
                if not data:
                    break
                chunk_sha.update(data)
                image_part = min(len(data), image_remaining)
                if image_part:
                    image_sha.update(data[:image_part])
                    image_remaining -= image_part
                if image_part < len(data) and any(data[image_part:]):
                    raise ValueError(f"nonzero data after original image end: {source}")
        sha = chunk_sha.hexdigest()
        chunks.append({"slot": slot, "name": name, "bytes": CHUNK_BYTES, "sha256": sha})
        print(f"HASH {slot:03d} {sha}", flush=True)
    if image_remaining or image_sha.hexdigest() != IMAGE_SHA256:
        raise ValueError(f"concatenated chunks differ from pinned original image: {image_sha.hexdigest()}")
    manifest = {
        "version": VERSION,
        "chunk_bytes": CHUNK_BYTES,
        "block_bytes": BLOCK_BYTES,
        "total_chunks": TOTAL_CHUNKS,
        "image_bytes": IMAGE_BYTES,
        "image_sha256": IMAGE_SHA256,
        "userdata_first_lba": USERDATA_FIRST,
        "userdata_last_lba": USERDATA_LAST,
        "recovery_first_lba": RECOVERY_FIRST,
        "chunks": chunks,
    }
    table = ["      // Generated by ci184-prepare.py manifest; full padded 64 MiB SHA256.",
             "      static const uint8_t expectedSha[totalChunks][SHA256_DIGEST_LENGTH] = {"]
    for entry in chunks:
        octets = ", ".join(f"0x{value:02x}" for value in bytes.fromhex(entry["sha256"]))
        table.append(f"        {{ {octets} }}, // {entry['slot']:03d}")
    table.append("      };\n")
    write_source_file(MANIFEST_PATH, json.dumps(manifest, indent=2) + "\n")
    write_source_file(HASH_TABLE_PATH, "\n".join(table))
    return manifest


def load_manifest():
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    constants = {
        "version": VERSION, "chunk_bytes": CHUNK_BYTES, "block_bytes": BLOCK_BYTES,
        "total_chunks": TOTAL_CHUNKS, "image_bytes": IMAGE_BYTES,
        "image_sha256": IMAGE_SHA256,
        "userdata_first_lba": USERDATA_FIRST, "userdata_last_lba": USERDATA_LAST,
        "recovery_first_lba": RECOVERY_FIRST,
    }
    for name, expected in constants.items():
        if manifest.get(name) != expected:
            raise ValueError(f"manifest {name} does not match CI184")
    chunks = manifest.get("chunks", [])
    if len(chunks) != TOTAL_CHUNKS:
        raise ValueError("manifest must contain 140 chunks")
    for slot, entry in enumerate(chunks):
        if entry.get("slot") != slot or entry.get("name") != f"chunk_{slot:03d}.bin" or entry.get("bytes") != CHUNK_BYTES:
            raise ValueError(f"manifest slot {slot} is invalid")
        if len(bytes.fromhex(entry["sha256"])) != 32:
            raise ValueError(f"manifest slot {slot} SHA256 is invalid")
    return manifest


def make_metadata(slot, mode, expected_sha):
    if mode not in MODE_VALUES or not 0 <= slot < TOTAL_CHUNKS:
        raise ValueError("invalid mode or slot")
    if mode == "repair" and slot >= 7:
        raise ValueError("repair is restricted to slots 0..6")
    if mode == "append" and slot < 7:
        raise ValueError("append is restricted to slots 7..139")
    expected_counter = 7 if mode == "repair" else slot
    fields = HEADER_FIELDS.pack(
        MAGIC, VERSION, HEADER_BYTES, slot, MODE_VALUES[mode], expected_counter,
        CHUNK_BYTES, bytes.fromhex(expected_sha), USERDATA_FIRST, USERDATA_LAST, RECOVERY_FIRST,
    )
    metadata = fields + hashlib.sha256(fields).digest()
    return metadata + bytes(BLOCK_BYTES - len(metadata))


def parse_metadata(metadata, manifest):
    if len(metadata) != BLOCK_BYTES:
        raise ValueError("metadata block has wrong size")
    magic, version, header_bytes, slot, mode_value, expected_counter, payload_bytes, payload_sha, first, last, recovery = HEADER_FIELDS.unpack_from(metadata)
    if magic != MAGIC or version != VERSION or header_bytes != HEADER_BYTES:
        raise ValueError("metadata magic/version/header size is invalid")
    if metadata[96:128] != hashlib.sha256(metadata[:96]).digest() or any(metadata[128:]):
        raise ValueError("metadata checksum or reserved bytes are invalid")
    modes = {value: name for name, value in MODE_VALUES.items()}
    if mode_value not in modes or not 0 <= slot < TOTAL_CHUNKS:
        raise ValueError("metadata mode/slot is invalid")
    mode = modes[mode_value]
    expected_sha = manifest["chunks"][slot]["sha256"]
    if metadata != make_metadata(slot, mode, expected_sha):
        raise ValueError("metadata fields do not match the pinned slot")
    return {"slot": slot, "mode": mode, "mode_value": mode_value,
            "expected_counter": expected_counter, "payload_bytes": payload_bytes,
            "sha256": payload_sha.hex(), "userdata_first_lba": first,
            "userdata_last_lba": last, "recovery_first_lba": recovery,
            "target_first_lba": first + slot * CHUNK_BLOCKS,
            "target_end_lba_exclusive": first + (slot + 1) * CHUNK_BLOCKS}


def verify_wrapped(path, manifest=None):
    manifest = load_manifest() if manifest is None else manifest
    path = Path(path)
    if path.stat().st_size != CHUNK_BYTES + BLOCK_BYTES:
        raise ValueError(f"wrapped payload must be {CHUNK_BYTES + BLOCK_BYTES} bytes")
    with path.open("rb") as source:
        source.seek(CHUNK_BYTES)
        metadata = source.read(BLOCK_BYTES)
    result = parse_metadata(metadata, manifest)
    actual = digest_file(path, CHUNK_BYTES)
    if actual != result["sha256"]:
        raise ValueError(f"payload SHA256 mismatch: {path}")
    result["file"] = str(path.resolve())
    return result


def wrap_chunk(chunks_dir, output_dir, slot, mode, manifest):
    source = Path(chunks_dir) / f"chunk_{slot:03d}.bin"
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    destination = output_dir / f"{mode}_{slot:03d}.bin"
    if source.resolve() == destination.resolve():
        raise ValueError("destination must not replace the original chunk")
    expected_sha = manifest["chunks"][slot]["sha256"]
    metadata = make_metadata(slot, mode, expected_sha)
    if source.stat().st_size != CHUNK_BYTES or digest_file(source) != expected_sha:
        raise ValueError(f"original chunk differs from pinned SHA256: {source}")
    if destination.exists():
        result = verify_wrapped(destination, manifest)
        if result["slot"] != slot or result["mode"] != mode:
            raise ValueError(f"existing output has different metadata: {destination}")
        print(f"REUSE {destination} slot={slot} mode={mode} sourceSHA256={expected_sha} targetLBA=0x{USERDATA_FIRST + slot * CHUNK_BLOCKS:x}", flush=True)
        return destination
    temporary = destination.with_name(destination.name + ".tmp-" + uuid.uuid4().hex)
    try:
        copied_sha = hashlib.sha256()
        with source.open("rb") as src, temporary.open("xb") as dst:
            while True:
                data = src.read(1024 * 1024)
                if not data:
                    break
                copied_sha.update(data)
                dst.write(data)
            if copied_sha.hexdigest() != expected_sha:
                raise ValueError(f"original chunk changed while wrapping: {source}")
            dst.write(metadata)
            dst.flush()
            os.fsync(dst.fileno())
        # Do not replace an output another process prepared in the meantime.
        if destination.exists():
            raise FileExistsError(destination)
        temporary.rename(destination)
    finally:
        temporary.unlink(missing_ok=True)
    print(f"WROTE {destination} bytes={CHUNK_BYTES + BLOCK_BYTES} slot={slot} mode={mode} sourceSHA256={expected_sha} targetLBA=0x{USERDATA_FIRST + slot * CHUNK_BLOCKS:x}", flush=True)
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("manifest", help="pin 140 original chunk hashes and write the C++ table")
    generate.add_argument("--chunks-dir", required=True, type=Path)
    wrap = commands.add_parser("wrap", help="append checked metadata to copied chunks")
    wrap.add_argument("--chunks-dir", required=True, type=Path)
    wrap.add_argument("--out-dir", required=True, type=Path)
    wrap.add_argument("--mode", required=True, choices=MODE_VALUES)
    selection = wrap.add_mutually_exclusive_group(required=True)
    selection.add_argument("--slot", type=int)
    selection.add_argument("--all", action="store_true")
    verify = commands.add_parser("verify", help="check complete payload and metadata")
    verify.add_argument("--file", required=True, type=Path)
    args = parser.parse_args()
    if args.command == "manifest":
        generate_manifest(args.chunks_dir)
    elif args.command == "verify":
        print(json.dumps(verify_wrapped(args.file), indent=2))
    else:
        manifest = load_manifest()
        slots = range(7) if args.mode == "repair" else range(7, TOTAL_CHUNKS)
        if args.slot is not None:
            slots = [args.slot]
        for slot in slots:
            # Validate before indexing the manifest.
            make_metadata(slot, args.mode, manifest["chunks"][slot]["sha256"] if 0 <= slot < TOTAL_CHUNKS else "00" * 32)
            wrap_chunk(args.chunks_dir, args.out_dir, slot, args.mode, manifest)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)
